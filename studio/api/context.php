<?php
// studio/api/context.php — ИИ у выделения в AI Чертежи (кнопка «ИИ» справа в панели инструментов,
// «ИИ у выделения…» в контекстном меню чертежа, Ctrl+Alt+Пробел). Подключается из assistant.php для
// запросов {mode: "text", op, custom?, extra?, selection, document}.
//
// Модель видит все надписи чертежа, а меняет только выделенные надписи (однострочный и многострочный
// текст, атрибуты). Большой чертёж передаётся не целиком: начало, короткие строки-заголовки и окно
// вокруг выделения.

declare(strict_types=1);

/** Сколько токенов документа (≈ символов / 3,5) отдавать целиком. */
const STUDIO_CONTEXT_TOKENS = 16000;
/** Сколько символов брать по обе стороны от выделения в большом документе. */
const STUDIO_CONTEXT_WINDOW = 3000;
/** Больше этого текст документа не принимаем вовсе. */
const STUDIO_CONTEXT_MAX_CHARS = 2000000;

/** Задания операций меню. Ключи — id пунктов меню в studio.js. */
function studio_context_prompt(string $op): ?string
{
    $only = ' Верни ТОЛЬКО результат, без вступлений и пояснений.';
    $p = [
        'fix_grammar' => 'Исправь орфографические, пунктуационные и грамматические ошибки в надписи чертежа. Термины, обозначения, размеры, марки материалов и номера ГОСТ не меняй.' . $only,
        'improve' => 'Поправь надпись чертежа: ясно, коротко, технически грамотно, в стиле конструкторской документации (ЕСКД). Сохрани смысл, числа, обозначения и ссылки на стандарты.' . $only,
        'eskd_abbr' => 'Приведи надпись к правилам ГОСТ 2.316 и ГОСТ 2.321: допустимые сокращения слов (черт., поз., шт., max, min, отв., черт. и т. п.), единицы величин по ГОСТ 8.417, без произвольных сокращений. Не меняй смысл и числа.' . $only,
        'shorten' => 'Сократи надпись, сохранив смысл, числа и обозначения: для чертежа надписи должны быть краткими.' . $only,
        'upper' => 'Перепиши надпись прописными буквами (как пишут заголовки и наименования на чертежах), исправив ошибки, если они есть.' . $only,
        'tech_req' => 'Оформи технические требования чертежа по ГОСТ 2.316: пронумерованные пункты «1. …», каждый — одно требование, в принятом порядке (требования к материалу и заготовке; к размерам, предельным отклонениям, форме и расположению поверхностей; к покрытиям и отделке; прочие). Без заголовка «Технические требования» (его ставят только при наличии таблицы). Если исходный текст — черновик или список пожеланий, сформулируй его требованиями; ничего не выдумывай сверх смысла.' . $only,
        'note' => 'Оформи примечание к чертежу: кратко, в стиле ЕСКД; если пунктов несколько — пронумеруй.' . $only,
        'title_name' => 'Сформулируй наименование изделия для основной надписи (графа 1) по ГОСТ 2.104 и ГОСТ 2.109: имя существительное в именительном падеже единственного числа на первом месте («Вал», «Корпус подшипника», «Кронштейн»), без лишних слов. Предложи 3 варианта нумерованным списком.' . $only,
        'to_list' => 'Разбей текст на пронумерованные пункты «1. …» (как технические требования на чертеже).' . $only,
        'check_text' => 'Проверь надписи чертежа: орфография, сокращения (ГОСТ 2.316), единицы величин, единообразие терминов. Перечисли замечания списком Markdown: «было → стало» и коротко почему. Если замечаний нет, напиши «Замечаний нет».',
        'summarize' => 'По надписям чертежа кратко опиши, что это за чертёж: изделие, назначение, основные требования. 3–6 пунктов маркированным списком Markdown.' . $only,
        'explain' => 'Объясни простыми словами, что означают эти надписи и обозначения на чертеже (термины, сокращения, ссылки на стандарты).',
    ];
    $langs = ['translate_ru' => 'русский', 'translate_en' => 'английский', 'translate_be' => 'белорусский',
        'translate_de' => 'немецкий', 'translate_zh' => 'китайский'];
    if (isset($langs[$op])) {
        return "Переведи надпись чертежа на {$langs[$op]} язык технической терминологией. Числа, обозначения, марки материалов и номера стандартов оставь как есть." . $only;
    }
    return $p[$op] ?? null;
}

/** Операции, которым без выделения нужен весь документ. */
function studio_context_whole_doc_ops(): array
{
    return ['check_text', 'summarize', 'explain', 'tech_req', 'note', 'title_name'];
}

/** Документ целиком или (если велик) начало, оглавление и окно вокруг выделения. */
function studio_context_block(string $doc, string $selected): array
{
    $len = mb_strlen($doc, 'UTF-8');
    if ((int)($len / 3.5) <= STUDIO_CONTEXT_TOKENS) {
        return ['full', "=== ВСЕ НАДПИСИ ЧЕРТЕЖА ===\n" . $doc . "\n=== КОНЕЦ НАДПИСЕЙ ЧЕРТЕЖА ===\n"];
    }
    $anchor = (int)($len / 2);
    if ($selected !== '') {
        $probe = mb_substr($selected, 0, 200, 'UTF-8');
        $p = mb_strpos($doc, $probe, 0, 'UTF-8');
        if ($p !== false) {
            $anchor = $p + (int)(mb_strlen($selected, 'UTF-8') / 2);
        }
    }
    $start = max(0, $anchor - STUDIO_CONTEXT_WINDOW);
    $end = min($len, $anchor + STUDIO_CONTEXT_WINDOW);
    $toc = [];
    foreach (preg_split('/\R/u', $doc) ?: [] as $line) {
        $line = trim($line);
        if ($line === '' || mb_strlen($line, 'UTF-8') >= 100) {
            continue;
        }
        if (mb_strtoupper($line, 'UTF-8') === $line || !preg_match('/[.!?;:,]$/u', $line)) {
            $toc[] = '• ' . $line;
        }
        if (count($toc) >= 40) {
            break;
        }
    }
    $block = "=== НАДПИСЕЙ МНОГО: ПОКАЗАНЫ НАЧАЛО, КОРОТКИЕ СТРОКИ И ФРАГМЕНТ ВОКРУГ ВЫДЕЛЕНИЯ ===\n"
        . "--- Начало ---\n" . mb_substr($doc, 0, 800, 'UTF-8') . "\n"
        . "--- Оглавление ---\n" . implode("\n", $toc) . "\n"
        . "--- Фрагмент (символы {$start}–{$end} из {$len}) ---\n" . mb_substr($doc, $start, $end - $start, 'UTF-8') . "\n=== КОНЕЦ ===\n";
    return ['windowed', $block];
}

/**
 * Системная инструкция и сообщения для модели по запросу панели.
 * Возвращает [system, messages, contextMode]; при ошибке завершает запрос через studio_fail.
 */
function studio_context_request(array $in): array
{
    $op = is_string($in['op'] ?? null) ? trim($in['op']) : '';
    $custom = is_string($in['custom'] ?? null) ? trim(mb_substr($in['custom'], 0, 4000, 'UTF-8')) : '';
    $extra = is_string($in['extra'] ?? null) ? trim(mb_substr($in['extra'], 0, 2000, 'UTF-8')) : '';
    $selected = is_string($in['selection'] ?? null) ? $in['selection'] : '';
    $doc = is_string($in['document'] ?? null) ? $in['document'] : '';
    if (mb_strlen($doc, 'UTF-8') > STUDIO_CONTEXT_MAX_CHARS) {
        $doc = mb_substr($doc, 0, STUDIO_CONTEXT_MAX_CHARS, 'UTF-8');
    }
    $selected = mb_substr($selected, 0, 60000, 'UTF-8');

    if ($custom !== '') {
        $task = $custom;
    } else {
        $task = studio_context_prompt($op);
        if ($task === null) {
            studio_fail(400, 'Неизвестная операция: ' . $op);
        }
    }
    if ($extra !== '') {
        $task .= "\n\nДополнительное пожелание: " . $extra;
    }

    $system = implode("\n", [
        'Ты — ИИ-помощник, встроенный в программу черчения AI Чертежи (по возможностям как AutoCAD). Чертежи оформляются по ЕСКД.',
        'Ты видишь надписи чертежа (или их часть), но работаешь только с указанными надписями, если они заданы.',
        'Результат станет надписью на чертеже: коротко, без лишних пустых строк, кавычек вокруг ответа и пояснений.',
        'Отвечай без вступлений вроде «Вот ваш текст:», без извинений и комментариев о себе.',
        'Сохраняй язык исходного текста, если задача — не перевод. Десятичный разделитель — запятая (ГОСТ 2.304).',
        'Для списков, таблиц и подзаголовков используй Markdown; обычный текст пиши обычными абзацами.',
    ]);
    [$mode, $context] = studio_context_block($doc, $selected);
    if ($selected !== '') {
        $target = "=== НАДПИСИ, С КОТОРЫМИ РАБОТАЕМ ===\n" . $selected . "\n=== КОНЕЦ ===\n\n"
            . 'Выполни задачу ТОЛЬКО для этих надписей; остальные надписи чертежа выше — контекст.';
    } elseif (in_array($op, studio_context_whole_doc_ops(), true) || $custom !== '') {
        $target = 'Надписи не выделены: работай с чертежом целиком (по его надписям).';
    } else {
        $target = 'Выделения нет: выполни задачу для показанного текста.';
    }
    $user = ($doc !== '' ? $context . "\n" : '') . $target . "\n\n=== ЗАДАЧА ===\n" . $task;
    return [$system, [['role' => 'user', 'content' => $user]], $mode];
}
