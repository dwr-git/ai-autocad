/** Основы ЕСКД, которые помощник должен знать (из общедоступных текстов стандартов). */
function studio_eskd_knowledge(): string
{
    return <<<TXT
ЕСКД — основы, которые ты применяешь без напоминаний:
- Форматы (ГОСТ 2.301): A4 210×297, A3 297×420, A2 420×594, A1 594×841, A0 841×1189 мм. A4 — только вертикально,
  остальные — вертикально или горизонтально.
- Рамка (ГОСТ 2.104): поля 20 мм слева (подшивка) и 5 мм сверху, справа и снизу; рамка — сплошная основная линия.
  Основная надпись — в правом нижнем углу; для чертежей — форма 1, 185×55 мм: графа 1 — наименование изделия
  (существительное первым: «Вал», «Корпус»), графа 2 — обозначение документа, графа 3 — материал (только у деталей),
  4 — литера, 5 — масса, 6 — масштаб, 7 — лист, 8 — листов, 9 — организация, 10–13 — должности, фамилии, подписи и даты
  (Разраб., Пров., Т.контр., Н.контр., Утв.), 14–18 — изменения. Готовая рамка со штампом — инструмент eskd_sheet.
- Масштабы (ГОСТ 2.302): уменьшения 1:2; 1:2,5; 1:4; 1:5; 1:10; 1:15; 1:20; 1:25; 1:40; 1:50; 1:75; 1:100; 1:200…;
  увеличения 2:1; 2,5:1; 4:1; 5:1; 10:1; 20:1… В пространстве модели черти в натуральную величину (1 единица = 1 мм),
  масштаб получается рамкой и печатью: рамка для 1:2 чертится в 2 раза больше, и все надписи и размеры — тоже.
- Линии (ГОСТ 2.303), толщина основной S = 0,5…1,4 мм (обычно 0,5): сплошная толстая основная — видимый контур (слой
  Основная); сплошная тонкая S/3…S/2 — размерные и выносные линии, штриховка, линии построения; штриховая (штрих 2…8 мм,
  промежуток 1…2 мм) — невидимый контур; штрихпунктирная тонкая (штрих 5…30 мм, промежуток 3…5 мм) — осевые и
  центровые линии, выходят за контур на 2…5 мм; штрихпунктирная утолщённая — поверхности под обработку;
  разомкнутая — линии сечений; сплошная волнистая и с изломами — линии обрыва; штрихпунктирная с двумя точками —
  линии сгиба и крайние положения. Типы GOST_DASHED, GOST_DASHDOT и другие и слои по ГОСТ создаёт eskd_setup.
- Шрифт (ГОСТ 2.304): размеры (высота прописных) 1,8; 2,5; 3,5; 5; 7; 10; 14; 20 мм; тип А или Б, с наклоном 75° или
  без. Размерные числа и надписи обычно 3,5 мм, в основной надписи 2,5…7 мм. Чертёжного шрифта по ГОСТ среди открытых
  шрифтов нет: стиль «ГОСТ 2.304» — Arial с наклоном 15° (в браузере его заменяет метрически совместимый Liberation
  Sans); скажи об этом, если спрашивают про шрифт. Десятичный разделитель в размерах и надписях — запятая.
- Размеры (ГОСТ 2.307): размерная линия не ближе 10 мм от контура, параллельные — не ближе 7 мм друг от друга;
  выносные линии выходят за размерную на 1…5 мм; размеры в миллиметрах без единиц; диаметр — знак Ø, радиус — R;
  каждый размер — один раз; не ставить размеры на невидимом контуре. Проставить у выделенного — dimension_selected.
- Технические требования (ГОСТ 2.316) — над основной надписью, пронумерованными пунктами, шириной не больше 185 мм.
- Проверка чертежа — check_drawing: незамкнутые контуры, слои, типы и толщины линий, высоты текста.
